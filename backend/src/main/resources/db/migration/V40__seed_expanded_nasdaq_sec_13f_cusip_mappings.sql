    stock_id,
    identifier_type,
    identifier_value,
    issuer_name,
    source,
    confidence,
    active,
    created_at,
    updated_at
)
SELECT
    s.stock_id,
    'CUSIP',
    m.cusip,
    m.issuer_name,
    'SEC_13F_AUTO_EXPANDED_TITLE_SAFE',
    m.confidence,
    TRUE,
    NOW(6),
    NOW(6)
FROM tmp_sec_13f_nasdaq_cusip_mapping_expanded m
JOIN stock s ON UPPER(s.stock_code) = m.stock_code
JOIN exchange e ON e.exchange_id = s.exchange_id
LEFT JOIN stock_security_identifier existing_stock
    ON existing_stock.stock_id = s.stock_id
    AND existing_stock.identifier_type = 'CUSIP'
    AND existing_stock.active = TRUE
LEFT JOIN stock_security_identifier existing_cusip
    ON existing_cusip.identifier_type = 'CUSIP'
    AND existing_cusip.identifier_value = m.cusip
    AND existing_cusip.active = TRUE
WHERE UPPER(e.code) = 'NASDAQ'
    AND existing_stock.stock_security_identifier_id IS NULL
    AND existing_cusip.stock_security_identifier_id IS NULL
